import { lstat, readdir, rm, rmdir } from 'node:fs/promises';
import path from 'node:path';
import { pathExists } from '../path-exists.js';
import type { Io } from '../setup/types.js';
import type { DiscoveredInstall } from './types.js';

/**
 * Result of executing deterministic harness removal against an installation.
 */
export interface RemovalResult {
  root: string;
  removed: string[];
  failed: Array<{ path: string; error: string }>;
  preservedDocs: string[];
  remainingIntertwined: string[];
}

/** Options configuring removal reporting and behavior. */
export interface RemovalOptions {
  verbose?: boolean;
  io?: Io;
}

/** True when candidate equals target or is located strictly inside target. */
function isInsideOrEqual(candidate: string, target: string): boolean {
  const rel = path.relative(target, candidate);
  return rel === '' || (!rel.startsWith('..') && !path.isAbsolute(rel));
}

/** True when a path must be protected from deterministic removal. */
function isProtectedPath(candidate: string, install: DiscoveredInstall): boolean {
  const resolved = path.resolve(candidate);

  // invariant: explicitly preserved documentation directories must never be deleted.
  for (const docDir of install.preservedDocs ?? []) {
    if (isInsideOrEqual(resolved, path.resolve(docDir))) {
      return true;
    }
  }

  // invariant: documentation directories under install root or harnessHome are strictly preserved.
  const rootDocs = path.resolve(install.root, 'docs');
  if (isInsideOrEqual(resolved, rootDocs)) {
    return true;
  }
  const homeDocs = path.resolve(install.harnessHome, 'docs');
  if (isInsideOrEqual(resolved, homeDocs)) {
    return true;
  }

  // invariant: intertwined shared repository files must never be removed.
  for (const sharedFile of install.intertwinedFiles ?? []) {
    if (isInsideOrEqual(resolved, path.resolve(sharedFile))) {
      return true;
    }
  }

  // invariant: known repository shared files at root must never be modified by deterministic removal.
  const rootPackageJson = path.resolve(install.root, 'package.json');
  if (resolved === rootPackageJson) return true;

  const rootAgentsMd = path.resolve(install.root, 'AGENTS.md');
  if (resolved === rootAgentsMd) return true;

  const rootGitignore = path.resolve(install.root, '.gitignore');
  if (resolved === rootGitignore) return true;

  const rootWorkflows = path.resolve(install.root, '.github', 'workflows');
  if (isInsideOrEqual(resolved, rootWorkflows)) return true;

  return false;
}

/** Prunes empty parent directories up to install root. */
async function cleanupEmptyParents(
  removedArtifacts: string[],
  install: DiscoveredInstall,
  options?: RemovalOptions,
): Promise<void> {
  const candidateDirs = new Set<string>();
  const rootResolved = path.resolve(install.root);
  const homeResolved = path.resolve(install.harnessHome);

  for (const removedPath of removedArtifacts) {
    let current = path.dirname(path.resolve(removedPath));
    while (current !== rootResolved && current !== path.dirname(current)) {
      if (isInsideOrEqual(current, rootResolved) || isInsideOrEqual(current, homeResolved)) {
        // hazard: never prune harnessHome when it lives in a separate linked repository.
        if (current === homeResolved && homeResolved !== path.join(rootResolved, '.wolven-harness')) {
          break;
        }
        candidateDirs.add(current);
      } else {
        break;
      }
      current = path.dirname(current);
    }
  }

  const sortedCandidates = Array.from(candidateDirs).sort((a, b) => b.length - a.length);

  for (const dir of sortedCandidates) {
    // invariant: never delete preserved docs or directories holding existing preserved docs.
    const hasPreservedDocs = (install.preservedDocs ?? []).some(
      (docDir) => isInsideOrEqual(dir, path.resolve(docDir)) || isInsideOrEqual(path.resolve(docDir), dir),
    );
    if (hasPreservedDocs) {
      continue;
    }

    const homeDocs = path.resolve(install.harnessHome, 'docs');
    if ((await pathExists(homeDocs)) && isInsideOrEqual(homeDocs, dir)) {
      continue;
    }

    try {
      const stat = await lstat(dir);
      if (!stat.isDirectory()) continue;

      const entries = await readdir(dir);
      const nonIgnored = entries.filter((name) => name !== '.DS_Store');
      if (nonIgnored.length === 0) {
        // hazard: .DS_Store generated by macOS Finder would prevent rmdir on an otherwise empty directory.
        for (const entry of entries) {
          await rm(path.join(dir, entry), { force: true });
        }
        await rmdir(dir);
        if (options?.verbose && options?.io) {
          options.io.stdout.write(`Cleaned up empty directory: ${dir}\n`);
        }
      }
    } catch {
      // why: ignore directory removal failure on non-critical parent directories.
    }
  }
}

/**
 * Deterministically removes all harness-owned files and symlinks for an install,
 * strictly preserving docs directories and leaving shared files intact.
 */
export async function removeHarnessInstall(
  install: DiscoveredInstall,
  options?: RemovalOptions,
): Promise<RemovalResult> {
  const removed: string[] = [];
  const failed: Array<{ path: string; error: string }> = [];
  const artifacts = [...new Set(install.artifacts ?? [])];

  for (const artifact of artifacts) {
    const resolvedArtifact = path.isAbsolute(artifact) ? artifact : path.resolve(install.root, artifact);

    // invariant: docs directories and intertwined shared files must never be removed.
    if (isProtectedPath(resolvedArtifact, install)) {
      continue;
    }

    try {
      const stat = await lstat(resolvedArtifact);
      if (stat.isDirectory()) {
        await rm(resolvedArtifact, { recursive: true, force: false });
      } else {
        await rm(resolvedArtifact, { force: false });
      }
      removed.push(resolvedArtifact);
      if (options?.verbose && options?.io) {
        options.io.stdout.write(`Removed: ${resolvedArtifact}\n`);
      }
    } catch (error: unknown) {
      const message = error instanceof Error ? error.message : String(error);
      failed.push({ path: resolvedArtifact, error: message });
    }
  }

  await cleanupEmptyParents(removed, install, options);

  return {
    root: install.root,
    removed,
    failed,
    preservedDocs: [...(install.preservedDocs ?? [])],
    remainingIntertwined: [...(install.intertwinedFiles ?? [])],
  };
}

/**
 * Runs deterministic harness removal across all discovered installations.
 */
export async function removeLandscapes(
  installs: DiscoveredInstall[],
  options?: RemovalOptions,
): Promise<RemovalResult[]> {
  const results: RemovalResult[] = [];
  for (const install of installs) {
    results.push(await removeHarnessInstall(install, options));
  }
  return results;
}
